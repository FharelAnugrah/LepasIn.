import pg from 'pg';

const { Pool } = pg;

// Cegah pembuatan multiple connection pool saat hot-reloading di development
const globalForPg = globalThis;

if (!globalForPg._pgPool) {
  globalForPg._pgPool = new Pool({
    connectionString: process.env.DATABASE_URL || 'postgresql://postgres:postgres@localhost:5432/lepasin',
    max: 10,
    idleTimeoutMillis: 30000,
    connectionTimeoutMillis: 5000,
  });
}

export const pool = globalForPg._pgPool;

let isMigrationChecked = false;

async function ensureMigration() {
  if (isMigrationChecked) return;
  try {
    await pool.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS was_approved BOOLEAN DEFAULT FALSE');
    await pool.query("UPDATE users SET was_approved = TRUE WHERE seller_status = 'approved' AND was_approved IS NOT TRUE");
    await pool.query('ALTER TABLE users ADD COLUMN IF NOT EXISTS id_card_url TEXT');

    // Pastikan kolom gambar produk bertipe TEXT agar string Base64 Data URL tidak terpotong
    try {
      await pool.query('ALTER TABLE product_images ALTER COLUMN url TYPE TEXT');
    } catch (colErr) {
      console.warn('Migration product_images.url notice:', colErr.message);
    }

    try {
      await pool.query('ALTER TABLE order_items ALTER COLUMN product_image_url TYPE TEXT');
    } catch {
      // Abaikan jika order_items belum ada
    }
    
    // Tabel chats untuk fitur percakapan langsung antara Buyer dan Seller (baik pesanan COD maupun pra-order/tanya produk)
    await pool.query(`
      CREATE TABLE IF NOT EXISTS chats (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        order_id INT REFERENCES orders(id) ON DELETE CASCADE,
        store_id INT REFERENCES stores(id) ON DELETE CASCADE,
        product_id INT REFERENCES products(id) ON DELETE SET NULL,
        sender_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        receiver_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        message TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      ALTER TABLE chats ALTER COLUMN order_id DROP NOT NULL;
      ALTER TABLE chats ADD COLUMN IF NOT EXISTS store_id INT REFERENCES stores(id) ON DELETE CASCADE;
      ALTER TABLE chats ADD COLUMN IF NOT EXISTS product_id INT REFERENCES products(id) ON DELETE SET NULL;
      CREATE INDEX IF NOT EXISTS chats_order_idx ON chats (order_id, created_at ASC);
      CREATE INDEX IF NOT EXISTS chats_store_idx ON chats (store_id);
      CREATE INDEX IF NOT EXISTS chats_product_idx ON chats (product_id);
      CREATE INDEX IF NOT EXISTS chats_sender_idx ON chats (sender_id);
      CREATE INDEX IF NOT EXISTS chats_receiver_idx ON chats (receiver_id);
    `);

    isMigrationChecked = true;
  } catch (err) {
    console.error('Migration error in db.js:', err);
    // Abaikan jika tabel belum siap
  }
}

/**
 * Eksekusi parameterized query Raw SQL
 * @param {string} text Query SQL dengan $1, $2, dst.
 * @param {Array} params Parameter query
 * @returns {Promise<pg.QueryResult>}
 */
export async function query(text, params = []) {
  if (!isMigrationChecked && !text.includes('ALTER TABLE')) {
    await ensureMigration();
  }
  const start = Date.now();
  try {
    const res = await pool.query(text, params);
    return res;
  } catch (error) {
    console.error('Database query error:', {
      query: text.replace(/\s+/g, ' ').trim(),
      error: error.message,
    });
    throw error;
  }
}

/**
 * Ambil client untuk transaksi database manual
 * @returns {Promise<pg.PoolClient>}
 */
export async function getClient() {
  return await pool.connect();
}

/**
 * Eksekusi callback di dalam transaksi database atomik (BEGIN ... COMMIT / ROLLBACK)
 * @param {(client: pg.PoolClient) => Promise<any>} callback
 * @returns {Promise<any>}
 */
export async function withTransaction(callback) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await callback(client);
    await client.query('COMMIT');
    return result;
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}
